"""
hiper.evaluation.thor_world
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
THOR-Lifelong world generator (design.md, 'Benchmark: THOR-Lifelong').

One sequence = one iTHOR scene visited in N sessions. Between sessions a
ground-truth change process acts on the objects by AFFORDANCE GROUP only
(never by class; config/class_priors_indoor.yaml is not used here):

  pickupable  hazard 0.1/day * exp(1.0 z_j), z_j ~ N(0,1) once per sequence;
              a change relocates (60 %) or removes (40 %) the object; a
              removed object comes back at a random place with hazard 0.2/day.
  moveable    hazard 1/60 per day * exp(1.0 z_j); relocation only.
  fixed       never changes.

The process is a continuous-time Markov chain simulated exactly inside each
gap (several events may happen in one gap; only the net effect is applied).
Session 0 adds duplicates: 2 extra copies of 3 random pickupable types.

Simulator facts this module relies on (AI2-THOR 5.0.0, build a9ccb07f,
checked with probes before writing it):
  * pickupable objectIds encode the position and are re-generated by
    InitialRandomSpawn, so the stable identity is the Unity object ``name``
    (unique per scene; duplicates are named '<name>(Clone)_random_copy_<i>').
    gt_id = name everywhere.
  * an object disabled while InitialRandomSpawn runs is dropped from the
    scene registry and cannot be re-enabled. Disabled objects are therefore
    parked far below the floor (kinematic) and re-enabled around every
    InitialRandomSpawn call, then disabled again.
  * fieldOfView is vertical: fx = fy = (H/2) / tan(fov/2); depth is planar
    (z-depth) in metres.
  * fixed parts of a moveable (drawers of a dresser, shelves of a side
    table) are rigidly attached and move with it. They are detected by AABB
    containment and get group 'moveable' with ``attached_to`` = parent; they
    have no events of their own.

Frames: world frame right-handed z-up; Unity (x, y, z) -> (x, z, y).
Camera frame OpenCV (x right, y down, z forward); T_wc maps camera points
to world. Ground truth is always read back from simulator metadata after
the changes are applied, never taken from the intended change.

Everything above the ``ThorSim`` class is pure numpy and unit-tested
(tests/test_thor_world.py); ai2thor and cv2 are imported lazily.
"""

